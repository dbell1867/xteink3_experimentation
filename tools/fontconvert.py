#!/usr/bin/env python3
"""Convert a TrueType/OpenType font into an Adafruit GFX font laid out as
Windows-1252 (cp1252), bytes 0x20..0xFF.

Why not Adafruit's own fontconvert: Adafruit_GFX::write() takes ONE byte, so a
font can only have 256 slots. Adafruit's tool puts each glyph at its Unicode
code point (U+2019 can't fit in a byte). cp1252 = Latin-1 plus typographic
punctuation (curly quotes, dashes, ellipsis) in 0x80-0x9F, so we render the
Unicode glyph for each cp1252 byte and store it at that byte. The firmware
maps UTF-8 text to the same bytes.

Rendering matches Adafruit's tool: FreeType hinted, 1-bit (FT_LOAD_TARGET_MONO),
bits packed MSB-first, continuous across rows, each glyph starting on a byte.

Usage:
  pip install freetype-py pillow
  fontconvert.py FONT.ttf PIXEL_SIZE NAME > include/NAME.h
  fontconvert.py FONT.ttf PIXEL_SIZE NAME --preview out.png "sample text"
"""
import sys

import freetype

FIRST, LAST = 0x20, 0xFF


def cp1252_char(b):
    """The Unicode character for cp1252 byte b, or None for the 5 unused bytes."""
    if b == 0xA0:
        return " "  # no-break space: draw like a space
    try:
        return bytes([b]).decode("cp1252")
    except UnicodeDecodeError:
        return None  # 0x81, 0x8D, 0x8F, 0x90, 0x9D are undefined


def convert(path, px):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, px)
    y_advance = face.size.height >> 6
    bitmap, glyphs = [], []
    for b in range(FIRST, LAST + 1):
        ch = cp1252_char(b)
        if ch is None or face.get_char_index(ord(ch)) == 0:
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0, b, ch))
            continue
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO)
        g = face.glyph
        bm = g.bitmap
        offset = len(bitmap)
        acc, nbits = 0, 0
        for y in range(bm.rows):
            for x in range(bm.width):
                bit = (bm.buffer[y * bm.pitch + (x >> 3)] >> (7 - (x & 7))) & 1
                acc = (acc << 1) | bit
                nbits += 1
                if nbits == 8:
                    bitmap.append(acc)
                    acc, nbits = 0, 0
        if nbits:
            bitmap.append(acc << (8 - nbits))
        glyphs.append((offset, bm.width, bm.rows, g.advance.x >> 6, g.bitmap_left, 1 - g.bitmap_top, b, ch))
    return bitmap, glyphs, y_advance, face


def emit_header(name, path, px, bitmap, glyphs, y_advance, face):
    out = []
    out.append(f"// {name}: {face.family_name.decode()} {face.style_name.decode()}, {px} px em, "
               f"Adafruit GFX font in cp1252 order (0x{FIRST:02X}-0x{LAST:02X}).")
    out.append(f"// Generated by tools/fontconvert.py from {path.split('/')[-1]}.")
    out.append("// Noto Serif: SIL Open Font License 1.1 (see fonts/OFL.txt). Do not edit by hand.")
    out.append("#pragma once")
    out.append("#include <Adafruit_GFX.h>\n")
    out.append(f"const uint8_t {name}Bitmaps[] PROGMEM = {{")
    for i in range(0, len(bitmap), 16):
        out.append("    " + ", ".join(f"0x{v:02X}" for v in bitmap[i:i + 16]) + ",")
    out.append("};\n")
    out.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for (off, w, h, adv, xo, yo, b, ch) in glyphs:
        label = "unused" if ch is None else repr(ch)
        out.append(f"    {{{off:5d}, {w:3d}, {h:3d}, {adv:3d}, {xo:4d}, {yo:4d}}},  // 0x{b:02X} {label}")
    out.append("};\n")
    out.append(f"const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, "
               f"0x{FIRST:02X}, 0x{LAST:02X}, {y_advance}}};")
    out.append(f"// {len(bitmap)} bitmap bytes + {len(glyphs) * 7} glyph bytes")
    return "\n".join(out) + "\n"


def preview(bitmap, glyphs, y_advance, text, png):
    """Draw `text` exactly as Adafruit GFX would (glyph boxes from the tables)."""
    from PIL import Image
    data = text.encode("cp1252", errors="replace")
    lines = data.split(b"\n")
    W = 20 + max(sum(glyphs[c - FIRST][3] for c in ln if FIRST <= c <= LAST) for ln in lines)
    H = 20 + y_advance * len(lines)
    img = Image.new("1", (W, H), 1)
    px = img.load()
    y = 10 + y_advance * 3 // 4
    for ln in lines:
        x = 10
        for c in ln:
            if not FIRST <= c <= LAST:
                continue
            off, w, h, adv, xo, yo, _, _ = glyphs[c - FIRST]
            bit = 0
            for yy in range(h):
                for xx in range(w):
                    if (bitmap[off + (bit >> 3)] >> (7 - (bit & 7))) & 1:
                        px[x + xo + xx, y + yo + yy] = 0
                    bit += 1
            x += adv
        y += y_advance
    img.save(png)


if __name__ == "__main__":
    font, size, name = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    bm, gl, ya, face = convert(font, size)
    if "--preview" in sys.argv:
        i = sys.argv.index("--preview")
        preview(bm, gl, ya, sys.argv[i + 2].replace("\\n", "\n"), sys.argv[i + 1])
    else:
        sys.stdout.write(emit_header(name, font, size, bm, gl, ya, face))
